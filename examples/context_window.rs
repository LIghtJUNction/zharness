use zharness::{Error, context::{Budget, Context, Group, Message, Overflow}, zcall::v1::*};

fn main() -> Result<(), Error> {
    let system = [Content::text("Only use approved tools.")];
    let first = [Content::text("Earlier conversation")];
    let recent = [Content::text("Current question")];
    let summary = [Content::text("Application-provided summary; not generated by the library.")];
    let system_messages = [Message::new(Role::System, &system)];
    let first_messages = [Message::new(Role::User, &first)];
    let recent_messages = [Message::new(Role::User, &recent)];
    let summary_messages = [Message::new(Role::User, &summary)];
    let mut slots = [None; 4];
    // Illustrative caller-supplied costs, not a model tokenizer measurement.
    let mut context = Context::new(&mut slots, Budget { limit: 80, reserved: 20 })?;
    context.push(Group::new(0, &system_messages, 10).pinned(), Overflow::Reject)?;
    context.push(Group::new(1, &first_messages, 30), Overflow::Reject)?;
    let change = context.push(Group::new(2, &recent_messages, 30), Overflow::EvictOldest)?;
    assert_eq!(change.removed_groups, 1);
    assert!(context.groups().map(|g| g.id).eq([0, 2]));
    context.compact(1..2, Group::new(3, &summary_messages, 8))?;
    let mut branch_slots = [None; 4];
    let mut branch = context.fork_into(&mut branch_slots)?;
    branch.push(Group::new(4, &recent_messages, 30), Overflow::Reject)?;
    assert_eq!(context.len(), 2); assert_eq!(branch.len(), 3);
    let mut records = RecordStorage::<16>::new();
    let mut request = branch.build(Protocol::OpenAiChat.into(), Presence::Value(Text::new("model-x")), &mut records, &[])?;
    let mut output = [0; 2048];
    let report = request.encode(Protocol::OpenAiChat.into(), &mut output, &mut [0; 1024], &mut TokenStorage::<128>::new(), EncodeContext::default(), Policy::default())?;
    println!("{}", core::str::from_utf8(&output[..report.written]).expect("encoder produces UTF-8"));
    Ok(())
}
